// 습관: 틀린 줄 몰라서가 아니라 편해서, 또는 늘 그렇게 써서 생기는 실수. 사람 단위로 일관된다.

import { isSyllable, decompose } from '../hangul.js';

const syl = (ch) => (isSyllable(ch) ? decompose(ch) : null);
const jongIn = (ch, ...jongs) => jongs.includes(syl(ch)?.jong);

// ── 띄어 쓸 곳을 붙임 ──
// 뒤에 오는 글자가 이것이면 낱말이 거기서 끝난 것으로 본다 (조사·어미가 붙는 것까지 허용)
const END = '(?=[^가-힣]|$|[이가을를은는도만에야예라면니지씩째의간])';

// 패턴으로 찾는 자리. replace가 null을 주면 그 자리는 건너뛴다.
export const SPACING_RULES = [
  {
    // 관형형(받침 ㄴ·ㄹ) 뒤 의존 명사: 하는 것, 할 수, 갈 때, 본 적, 만난 지, 할 줄, 아는 만큼
    regex: new RegExp(`([가-힣]) (것|거|수|때|적|지|줄|만큼|뿐|듯|대로)${END}`, 'g'),
    replace: (m) => {
      const need = { 수: ['ㄹ'], 때: ['ㄹ'], 적: ['ㄴ'], 지: ['ㄴ'] }[m[2]] ?? ['ㄴ', 'ㄹ'];
      return jongIn(m[1], ...need) ? m[1] + m[2] : null;
    },
  },
  {
    // -아/어 뒤 보조 용언: 먹어 보다, 써 줘, 놓아 두다, 잊어 버렸다, 보내 드릴게요
    regex: /([가-힣]) ((?:주|보|두)[다고며면세시었았는지기니려신셨십]|줘|줬|봐|봤|둬|뒀|놓[다고으아았는지기]|놔|놨|버리|버려|버렸|버릴|드리|드려|드렸|드릴|줄(?=[게래까께])|볼(?=[게래까께]))/g,
    replace: (m) => {
      const d = syl(m[1]);
      // 조사 "가·와"(이가 보인다, 친구와 봤다)는 빼고, 받침 없는 -아/어 꼴만
      const ok = d && d.jong === '' && (['ㅓ', 'ㅕ', 'ㅐ', 'ㅝ'].includes(d.jung) || ['아', '봐', '놔'].includes(m[1]));
      return ok ? m[1] + m[2] : null;
    },
  },
  {
    // 수 관형사 + 단위 명사: 한 개, 두 시간, 세 명, 몇 번
    regex: new RegExp(`(?<![가-힣])(한|두|세|네|다섯|여섯|일곱|여덟|아홉|열|스무|몇) (개|명|번|시간|분|살|권|잔|병|마리|장|대|가지|군데|달|주|주일|시|층|사람|곳|통|켤레)${END}`, 'g'),
    replace: (m) => m[1] + m[2],
  },
];

// ── 붙여 쓸 곳을 띄움 (낱말 하나 안에서) ──
// 붙임보다 덜 일관되게 나타난다 (HABIT_CONSISTENCY.split)
const SPLIT_SKIP = ['어떡', '어떻', '그렇', '이렇', '저렇', '아무렇'];
export const SPLIT_RULES = [
  {
    // 명사 + 하다: 공부하다 → 공부 하다, 안녕하세요 → 안녕 하세요, 좋아해 → 좋아 해
    rule: '하다',
    regex: /(?<![가-힣])([가-힣]{2,}?)((?:하|해|했|합)[가-힣]*)(?![가-힣])/g,
    replace: (m) => (SPLIT_SKIP.includes(m[1]) ? null : `${m[1]} ${m[2]}`),
  },
  {
    // 명사 + 조사: 학교에서 → 학교 에서, 내일까지 → 내일 까지
    rule: '조사',
    regex: /(?<![가-힣])([가-힣]{2,}?)(에서|에게|한테|까지|부터|처럼|이랑)(?![가-힣])/g,
    replace: (m) => `${m[1]} ${m[2]}`,
  },
];

