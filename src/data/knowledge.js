// id    : 틀린 형태를 대표하는 이름 (CLI --mis 로 강제 지정할 때 쓴다)
// kind  : 표기(철자를 모름) | 어휘(뜻을 헷갈림)
// risk  : low = 읽는 사람이 원래 뜻을 바로 안다, high = 오해 소지가 있어 높은 레벨에서만
// pairs : [맞는 형태, 틀린 형태] — 긴 것부터 먼저 바꾼다. 부분 문자열로 찾으므로
//         다른 낱말 속에 우연히 들어가기 쉬운 짧은 형태는 피하고 앞뒤 글자를 붙여 좁힌다.
// rule  : pairs로 표현하기 어려운 경우의 정규식 규칙
// example: rule을 쓰는 항목의 [맞는 형태, 틀린 형태] 예 (리포트에 보여 줄 때 쓴다)
//
// 참고: 국립국어원 "자주 틀리는 맞춤법"·온라인 가나다, 표준국어대사전 외래어 표기 용례에서
//       많이 알려진 것을 골랐다. 틀린 형태는 실제로 많이 보이는 형태로 적었다.

import { decompose, compose, isSyllable } from '../hangul.js';

const jongOf = (ch) => (isSyllable(ch) ? decompose(ch).jong : null);

// ㄹ 받침 뒤 어미의 예사소리를 된소리로 (할게 → 할께, 할걸 → 할껄)
const tensedAfterRieul = (plain, tense) => ({
  regex: new RegExp(`([가-힣])${plain}(?=요|[\\s.!?~,]|$)`, 'g'),
  replace: (m) => (jongOf(m[1]) === 'ㄹ' ? `${m[1]}${tense}` : null),
});

const t = (id, pairs, risk = 'low') => ({ id, kind: '표기', risk, pairs });
const v = (id, pairs, risk = 'low') => ({ id, kind: '어휘', risk, pairs });

